#!/usr/bin/env python3
"""Build the small embedded fonts and write source/fonts_data.inc.

Inputs (downloaded once, not committed):
  Roboto Flex variable TTF        https://github.com/google/fonts/tree/main/ofl/robotoflex
  Material Symbols Rounded TTF    https://github.com/google/material-design-icons/tree/master/variablefont

Usage: tools/make_fonts.py ROBOTO_FLEX.ttf MATERIAL_SYMBOLS_ROUNDED.ttf
Needs fonttools (python3 -m venv .venv && .venv/bin/pip install fonttools).
"""
import io
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "source", "fonts_data.inc")

# Latin-1, Cyrillic, general punctuation, degree, arrows used in labels.
TEXT_RANGES = [(0x20, 0x7E), (0xA0, 0xFF), (0x400, 0x45F), (0x2010, 0x2027), (0x2030, 0x203A), (0x2190, 0x2193)]

# Material Symbols code points the UI draws (namespace icon in source/ui.cpp).
ICONS = {
    "headphones": 0xF01F, "headset_off": 0xE33A, "wifi": 0xE63E, "wifi_off": 0xE648,
    "network_wifi_1_bar": 0xEBE4, "network_wifi_2_bar": 0xEBD6, "network_wifi_3_bar": 0xEBE1,
    "signal_wifi_4_bar": 0xF065, "lan": 0xEB2F, "flight": 0xE539,
    "speed": 0xE9E4, "battery_charging_full": 0xE1A3, "light_mode": 0xE518,
    "volume_up": 0xE050, "volume_down": 0xE04D, "volume_off": 0xE04F,
    "power_settings_new": 0xF8C7, "restart_alt": 0xF053, "chevron_right": 0xE5CC,
    "arrow_back": 0xE5C4, "layers": 0xE53B, "bolt": 0xEA0B,
    "bluetooth": 0xE1A7, "bluetooth_disabled": 0xE1A9,
}


def instance(path, axes):
    """Static instance: every axis pinned (given value or the font default)."""
    font = TTFont(path)
    pinned = {a.axisTag: a.defaultValue for a in font["fvar"].axes}
    pinned.update(axes)
    return instancer.instantiateVariableFont(font, pinned, inplace=False)


def subset_font(font, unicodes):
    opts = subset.Options()
    opts.layout_features = ["kern", "liga", "calt"]
    opts.name_IDs = [1, 2]
    opts.notdef_outline = True
    opts.hinting = False
    opts.desubroutinize = True
    s = subset.Subsetter(opts)
    s.populate(unicodes=unicodes)
    s.subset(font)
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()


def c_array(name, data):
    lines = [f"alignas(4) static const unsigned char {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    roboto, symbols = sys.argv[1], sys.argv[2]
    text_cps = [c for lo, hi in TEXT_RANGES for c in range(lo, hi + 1)]

    regular = subset_font(instance(roboto, {"wght": 430, "wdth": 100, "opsz": 16, "slnt": 0, "GRAD": 0}), text_cps)
    medium = subset_font(instance(roboto, {"wght": 580, "wdth": 100, "opsz": 16, "slnt": 0, "GRAD": 0}), text_cps)
    icons = subset_font(instance(symbols, {"FILL": 1, "wght": 500, "GRAD": 0, "opsz": 24}), list(ICONS.values()))

    with open(OUT, "w") as f:
        f.write("// Generated by tools/make_fonts.py. Roboto Flex and Material Symbols, both\n")
        f.write("// under their own licenses (see fonts/). Do not edit by hand.\n\n")
        f.write(c_array("kFontRegular", regular) + "\n\n")
        f.write(c_array("kFontMedium", medium) + "\n\n")
        f.write(c_array("kFontIcons", icons) + "\n")
    print(f"regular {len(regular)} B, medium {len(medium)} B, icons {len(icons)} B -> {OUT}")


if __name__ == "__main__":
    main()
